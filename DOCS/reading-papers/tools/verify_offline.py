#!/usr/bin/env python3
"""Do the rewritten pages actually render offline?

A `_files/` directory beside the html is not proof. What matters is that every local reference
in the markup resolves to a file that exists, and that the CSS is real CSS rather than an error
page saved under a .css name. This opens each page and checks exactly that.

    python verify_offline.py
"""
from __future__ import annotations
import io
import os
import sys
from urllib.parse import unquote

from bs4 import BeautifulSoup

HERE = os.path.dirname(os.path.abspath(__file__))
REFS = os.path.abspath(os.path.join(HERE, "..", "blueprint-references"))


# References that are missing for a reason, and whose absence changes nothing on screen.
# Reporting them as breakage sends you chasing analytics scripts.
TRACKERS = ("matomo", "gtm.js", "google-analytics", "googletagmanager", "gtag",
            "segment.", "hotjar", "mixpanel", "doubleclick", "facebook.net/en_US/fbevents")


def is_tracking_pixel(tag) -> bool:
    """A 1x1 image hidden from the page and from screen readers is a beacon, not a picture."""
    if tag.name != "img":
        return False
    w, h = str(tag.get("width", "")), str(tag.get("height", ""))
    hidden = tag.get("aria-hidden") == "true" or "display: none" in str(tag.get("style", ""))
    return w == "1" and h == "1" and hidden


def check(html_path: str):
    d = os.path.dirname(html_path)
    raw = io.open(html_path, encoding="utf-8", errors="replace").read()
    soup = BeautifulSoup(raw, "lxml")
    local = missing = remote = 0
    excused = 0

    def look(val, tag=None):
        nonlocal local, missing, remote, excused
        if not val or val.startswith(("data:", "#", "mailto:", "javascript:")):
            return
        # A blob: URL is generated by JavaScript at run time and lives only in that browser
        # session. There is no server copy to fetch - not now, not ever.
        if val.startswith("blob:"):
            excused += 1
            return
        if tag is not None and is_tracking_pixel(tag):
            excused += 1
            return
        if any(t in val.lower() for t in TRACKERS):
            excused += 1
            return
        if val.startswith(("http://", "https://", "//")):
            remote += 1
            return
        local += 1
        # Try the path as written FIRST. Stripping at '#' assumes a URL fragment, but these
        # filenames legitimately contain '#' - "...(kubernetes#43783)_files/..." - and the
        # strip turned 35 perfectly good references into 35 fake failures.
        cand = unquote(val)
        for c in (cand, cand.split("?")[0], cand.split("#")[0]):
            if os.path.exists(os.path.join(d, c)):
                return
        missing += 1

    for t in soup.find_all("img"):
        look(t.get("src"), t)
    for t in soup.find_all("link"):
        if "stylesheet" in (t.get("rel") or []):
            look(t.get("href"), t)
    for t in soup.find_all("script"):
        look(t.get("src"), t)

    # a stylesheet that is really an HTML error page renders nothing
    bad_css = []
    fd = os.path.splitext(html_path)[0] + "_files"
    if os.path.isdir(fd):
        for f in os.listdir(fd):
            if f.endswith(".css"):
                head = io.open(os.path.join(fd, f), encoding="utf-8",
                               errors="replace").read(200).lstrip().lower()
                if head.startswith(("<!doctype", "<html")):
                    bad_css.append(f)
    return local, missing, remote, bad_css, excused


def main() -> int:
    pages = broken = tot_excused = 0
    problems = []
    for d in sorted(os.listdir(REFS)):
        full = os.path.join(REFS, d)
        if not os.path.isdir(full):
            continue
        for f in sorted(os.listdir(full)):
            if not f.lower().endswith(".html") or f.endswith(".orig.html"):
                continue
            p = os.path.join(full, f)
            local, missing, remote, bad_css, excused = check(p)
            pages += 1
            tot_excused += excused
            if missing or bad_css:
                broken += 1
                problems.append((d, f, local, missing, remote, bad_css))
    print("%d pages checked, %d with a broken CONTENT reference" % (pages, broken))
    print("%d references excused: blob: URLs, 1x1 tracking pixels and analytics scripts - "
          "none of them renders anything" % tot_excused)
    if problems:
        print()
        for d, f, local, missing, remote, bad_css in problems:
            print("  %-30s %-46s %d/%d local refs missing%s"
                  % (d[:30], f[:46], missing, local,
                     "; %d bogus css" % len(bad_css) if bad_css else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
