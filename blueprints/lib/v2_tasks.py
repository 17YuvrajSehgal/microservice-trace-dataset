#!/usr/bin/env python3
"""Enumerate v2 runs into a task file, and refuse to list a run that cannot actually be measured.

WHY THIS EXISTS RATHER THAN A `ls` IN THE SBATCH
------------------------------------------------
The v1 task files were written by hand. That was fine for 17 runs and is not fine for 303: a
typo'd run id becomes a silently missing row in the results table, and a run whose CTF never
extracted looks identical to a run whose measurement failed. Both would be read as "the
blueprint had nothing to say about that family".

So this checks each candidate before listing it — CTF directory present, metadata present,
ground truth present — and reports what it dropped and why. A task file from here is a promise
that every line is runnable.

The v2 layout differs from v1's, which is the other reason the old task files cannot be reused:

    v1   /scratch/.../data/l0/<app>/<run_id>/ctf          + ground_truth.json beside it
    v2   /scratch/.../data/stratatrace-v2/<app>/<fam>/<run_id>/kernel/kernel

    python3 v2_tasks.py --families noisy_neighbor,anomaly_cpu,svc_cpu_cap,normal \
        --out blueprints/lib/tasks-v2-cpu.txt
"""
from __future__ import annotations

import argparse
import os
import sys

V2 = os.environ.get("V2_ROOT", "/scratch/yuvraj17/stratatrace/data/stratatrace-v2")
APPS = ("sockshop", "trainticket")

# Not a fault family: the Prometheus snapshot archive extracts into a sibling directory of the
# same depth. Enumerating it would produce task lines for runs that do not exist.
NOT_A_FAMILY = {"prometheus"}


def is_aux(name):
    """Per-run sidecars, not runs. They sit at run depth inside each family directory."""
    return name.endswith("_metrics") or name.endswith("_load.csv") or name.endswith("_load.log")


def ctf_dir(app, fam, run):
    return os.path.join(V2, app, fam, run, "kernel", "kernel")


def check(app, fam, run):
    """Return None if runnable, else the reason it is not."""
    d = ctf_dir(app, fam, run)
    if not os.path.isdir(d):
        return "no CTF dir"
    if not os.path.exists(os.path.join(d, "metadata")):
        return "no CTF metadata"
    # One channel file is enough to know the stream survived extraction; babeltrace will
    # complain about the rest if they did not.
    if not any(f.startswith("channel") for f in os.listdir(d)):
        return "no channel streams"
    if any(f.endswith(".gz") for f in os.listdir(d)):
        return "still gzipped - babeltrace cannot read it"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--families", required=True,
                    help="comma-separated family names, or 'all'")
    ap.add_argument("--apps", default=",".join(APPS))
    ap.add_argument("--out", required=True)
    ap.add_argument("--header", default="", help="one-line note written into the task file")
    a = ap.parse_args()

    apps = [s.strip() for s in a.apps.split(",") if s.strip()]
    rows, dropped = [], []
    aux = 0            # per-run sidecars: counted, not listed
    per_family = {}

    for app in apps:
        app_root = os.path.join(V2, app)
        if not os.path.isdir(app_root):
            print(f"  WARNING: no such app tree: {app_root}", file=sys.stderr)
            continue
        available = sorted(f for f in os.listdir(app_root)
                           if os.path.isdir(os.path.join(app_root, f))
                           and f not in NOT_A_FAMILY)
        fams = available if a.families == "all" else \
            [s.strip() for s in a.families.split(",") if s.strip()]

        for fam in fams:
            fam_dir = os.path.join(app_root, fam)
            if not os.path.isdir(fam_dir):
                # A family absent from one application is a fact about the applications, not an
                # error: Train Ticket has no queue_backlog and no dns_delay.
                dropped.append((app, fam, "-", "family not present in this application"))
                continue
            runs = sorted(r for r in os.listdir(fam_dir)
                          if os.path.isdir(os.path.join(fam_dir, r)))
            for run in runs:
                # Sidecars are skipped SILENTLY. Listing them as drops was worse than
                # useless: 62 aux directories buried the report in noise, and a genuinely
                # broken run would have been invisible among them - the one thing this
                # check exists to catch.
                if is_aux(run):
                    aux += 1
                    continue
                why = check(app, fam, run)
                if why:
                    dropped.append((app, fam, run, why))
                else:
                    rows.append((app, fam, run))
                    per_family[(app, fam)] = per_family.get((app, fam), 0) + 1

    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("# v2 task file, generated by v2_tasks.py - every line was checked runnable\n")
        if a.header:
            fh.write(f"# {a.header}\n")
        fh.write(f"# families={a.families} apps={a.apps}\n#\n")
        fh.write("# APP FAMILY RUN_ID\n")
        for app, fam, run in rows:
            fh.write(f"{app} {fam} {run}\n")

    print(f"{len(rows)} runs -> {a.out}")
    for (app, fam), n in sorted(per_family.items()):
        print(f"  {app:12s} {fam:22s} {n:3d}")
    if aux:
        print(f"  ({aux} per-run sidecar dirs skipped - _metrics, _load.*)")
    if dropped:
        print(f"\n{len(dropped)} DROPPED - runs that cannot be measured:")
        for app, fam, run, why in dropped[:20]:
            print(f"  {app:12s} {fam:22s} {run:44s} {why}")
        if len(dropped) > 20:
            print(f"  ... and {len(dropped) - 20} more")
    return 0


if __name__ == "__main__":
    sys.exit(main())
