#!/usr/bin/env python3
"""Bulk outbound transfer at a steady rate, to a sink we control.

WHAT THIS IS AND IS NOT
-----------------------
A BENIGN SIMULATION on our own isolated VM. It sends generated bytes to a sink container we
start alongside it. Nothing leaves the host, no real data is read, and no external address is
contacted. What it reproduces is the SHAPE of bulk egress.

THE FIRST VERSION SENT TO 127.0.0.1 INSIDE ITS OWN CONTAINER, AND WAS INVISIBLE
------------------------------------------------------------------------------
Same safety properties, but the bytes never crossed an interface. Measured while it reported
sending 839 MB at 41.9 MB/s:

    container_network_transmit_bytes_total{name="data-exfiltration"}   0.0000
    node_network_transmit_bytes_total (host, non-loopback)             unchanged, 1.00x

So the fault had NO network signature at all - on either application - which is fatal for a
recipe whose stated question is whether a blueprint can tell unusual traffic from heavy
traffic. With no bytes on any counted interface, that question cannot even be asked.

Sending to a separate sink container keeps every safety property in the paragraph above and
puts the traffic on a real veth pair, where cAdvisor, the host bridge and the kernel's
net_dev_xmit all see it.

THE QUESTION IT ASKS
--------------------
Our network faults so far are about IMPAIRMENT - packets dropped, latency added. This is the
opposite: the network is working perfectly and is being used a lot. So it tests whether a
blueprint can tell UNUSUAL traffic from HEAVY traffic, which is a different question from any
we have asked, and one where the honest answer may well be "not from volume alone".

The distinguishing shape is steadiness and direction: a long-lived connection moving a large
volume one way at a constant rate, with almost no reply traffic. Application traffic is
bursty and bidirectional.

    python3 data_exfiltration.py [mbytes_per_s] [chunk_kb]
"""
import os
import socket
import sys
import threading
import time

RATE_MB = float(sys.argv[1]) if len(sys.argv) > 1 else 20.0
CHUNK_KB = int(sys.argv[2]) if len(sys.argv) > 2 else 64
# Where to send. "-" means run as the SINK and nothing else; anything else is a host to send to.
SINK_HOST = sys.argv[3] if len(sys.argv) > 3 else "127.0.0.1"
PORT = int(sys.argv[4]) if len(sys.argv) > 4 else 18097

stop = threading.Event()
sent = {"bytes": 0}
received = {"bytes": 0}


def sink():
    """A local listener: the traffic is real, but it never leaves the machine."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    s.bind(("0.0.0.0", PORT))
    s.listen(4)
    while not stop.is_set():
        try:
            c, _ = s.accept()
        except OSError:
            return
        threading.Thread(target=drain, args=(c,), daemon=True).start()


def drain(c):
    try:
        while not stop.is_set():
            b = c.recv(1 << 20)
            if not b:
                return
            received["bytes"] += len(b)
    except OSError:
        return
    finally:
        c.close()


def sender():
    chunk = os.urandom(CHUNK_KB * 1024)
    per_s = max(1, int(RATE_MB * 1024 / CHUNK_KB))     # chunks per second for the target rate
    while not stop.is_set():
        try:
            c = socket.create_connection((SINK_HOST, PORT), timeout=5)
        except OSError:
            time.sleep(1)
            continue
        try:
            while not stop.is_set():
                t0 = time.perf_counter()
                for _ in range(per_s):
                    c.sendall(chunk)                    # one direction, constant rate
                    sent["bytes"] += len(chunk)
                # pace it, so the rate is steady rather than a burst - steadiness is the tell
                delay = 1.0 - (time.perf_counter() - t0)
                if delay > 0:
                    time.sleep(delay)
        except OSError:
            pass
        finally:
            c.close()


def main():
    if SINK_HOST == "-":
        # Sink only. Counting received bytes here is the point: it is evidence from the other
        # end of the connection, not from the sender's own belief about what it sent.
        print(f"data_exfiltration sink: listening on 0.0.0.0:{PORT}, pid {os.getpid()}",
              flush=True)
        threading.Thread(target=sink, daemon=True).start()
        try:
            last = 0
            while True:
                time.sleep(10)
                mb = received["bytes"] / 1e6
                print(f"  received {mb:,.0f} MB total "
                      f"({(received['bytes'] - last) / 1e7:.1f} MB/s avg)", flush=True)
                last = received["bytes"]
        except KeyboardInterrupt:
            return
    print(f"data_exfiltration: {RATE_MB} MB/s in {CHUNK_KB} KB chunks to {SINK_HOST}:{PORT} "
          f"(a sink container on this host; nothing leaves it), pid {os.getpid()}", flush=True)
    threading.Thread(target=sender, daemon=True).start()
    try:
        last = 0
        while True:
            time.sleep(10)
            mb = sent["bytes"] / 1e6
            print(f"  sent {mb:,.0f} MB total ({(sent['bytes'] - last) / 1e7:.1f} MB/s avg)",
                  flush=True)
            last = sent["bytes"]
    except KeyboardInterrupt:
        stop.set()


if __name__ == "__main__":
    main()
