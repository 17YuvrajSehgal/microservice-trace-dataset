#!/usr/bin/env python3
"""Bulk outbound transfer at a steady rate, to a sink we control.

WHAT THIS IS AND IS NOT
-----------------------
A BENIGN SIMULATION on our own isolated VM. It sends generated bytes to a listener inside the
same container. Nothing leaves the host, no real data is read, and no external address is
contacted. What it reproduces is the SHAPE of bulk egress in a kernel trace.

THE QUESTION IT ASKS
--------------------
Our network faults so far are about IMPAIRMENT - packets dropped, latency added. This is the
opposite: the network is working perfectly and is being used a lot. So it tests whether a
blueprint can tell UNUSUAL traffic from HEAVY traffic, which is a different question from any
we have asked, and one where the honest answer may well be "not from volume alone".

The distinguishing shape is steadiness and direction: a long-lived connection moving a large
volume one way at a constant rate, with almost no reply traffic. Application traffic is
bursty and bidirectional.

    python3 data_exfiltration.py [mbytes_per_s] [chunk_kb]
"""
import os
import socket
import sys
import threading
import time

RATE_MB = float(sys.argv[1]) if len(sys.argv) > 1 else 20.0
CHUNK_KB = int(sys.argv[2]) if len(sys.argv) > 2 else 64
PORT = 18097

stop = threading.Event()
sent = {"bytes": 0}


def sink():
    """A local listener: the traffic is real, but it never leaves the machine."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    s.bind(("127.0.0.1", PORT))
    s.listen(4)
    while not stop.is_set():
        try:
            c, _ = s.accept()
        except OSError:
            return
        threading.Thread(target=drain, args=(c,), daemon=True).start()


def drain(c):
    try:
        while not stop.is_set():
            if not c.recv(1 << 20):
                return
    except OSError:
        return
    finally:
        c.close()


def sender():
    chunk = os.urandom(CHUNK_KB * 1024)
    per_s = max(1, int(RATE_MB * 1024 / CHUNK_KB))     # chunks per second for the target rate
    while not stop.is_set():
        try:
            c = socket.create_connection(("127.0.0.1", PORT), timeout=5)
        except OSError:
            time.sleep(1)
            continue
        try:
            while not stop.is_set():
                t0 = time.perf_counter()
                for _ in range(per_s):
                    c.sendall(chunk)                    # one direction, constant rate
                    sent["bytes"] += len(chunk)
                # pace it, so the rate is steady rather than a burst - steadiness is the tell
                delay = 1.0 - (time.perf_counter() - t0)
                if delay > 0:
                    time.sleep(delay)
        except OSError:
            pass
        finally:
            c.close()


def main():
    print(f"data_exfiltration: {RATE_MB} MB/s in {CHUNK_KB} KB chunks to a LOCAL sink "
          f"(nothing leaves the host), pid {os.getpid()}", flush=True)
    threading.Thread(target=sink, daemon=True).start()
    time.sleep(0.3)
    threading.Thread(target=sender, daemon=True).start()
    try:
        last = 0
        while True:
            time.sleep(10)
            mb = sent["bytes"] / 1e6
            print(f"  sent {mb:,.0f} MB total ({(sent['bytes'] - last) / 1e7:.1f} MB/s avg)",
                  flush=True)
            last = sent["bytes"]
    except KeyboardInterrupt:
        stop.set()


if __name__ == "__main__":
    main()
