#!/bin/bash
# Fault recipe: the disk of one database fills up.
#
# The database of one service (default carts-db, MongoDB) gets its own small filesystem. At
# injection a filler file takes every free byte. At cleanup the file is removed.
#
# WHY IT NEEDS ITS OWN FILESYSTEM. Every container here shares the VM's boot disk, which is
# also where LTTng writes the trace. Filling THAT would stop the tracer and the whole stack,
# and the run would record a dead machine, not this fault. So the database is moved onto a
# 1 GB loop-mounted ext4 file before tracing starts (`arm`), and only that is filled.
#
# STRATA_NEEDS_ARM - run_scenario.sh arms this recipe before tracing opens and disarms it after
# tracing ends, exactly as for the code-defect recipes. `arm` and `disarm` recreate the
# database container; `inject` and `cleanup` restart nothing.
#
# Pre-registered expectations (v3, CANDIDATE-PROBLEMS C1): LOGS name the cause in the
# database's own words ("No space left on device"); the KERNEL shows write calls returning
# -28 (ENOSPC) in one process; spans and metrics see the service that uses the database fail.
# What the database does when its disk is full (wait, refuse, or exit) is measured in the
# calibration, not assumed here.
#
# Usage:
#   ./disk_full.sh arm | inject [subtle|aggressive] | cleanup | disarm | status
#   env: TARGET_DB (carts-db)  VOL_MB (1024)
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/fault_lib.sh"

TARGET_DB="${TARGET_DB:-carts-db}"
VOL_MB="${VOL_MB:-1024}"
FAULT_FAMILY="B_service_resource"
FAULT_NAME="disk_full_${TARGET_DB}"
FAULT_SCOPE="service"
TARGET_SERVICE="$TARGET_DB"
EXPECTED_BLAST_RADIUS="${EXPECTED_BLAST_RADIUS:-[\"$TARGET_DB\", \"${TARGET_DB%-db}\", \"front-end\"]}"
EXPECTED_WINNING_MODALITY="${EXPECTED_WINNING_MODALITY:-logs}"
TARGET_TRACE_VISIBILITY="${TARGET_TRACE_VISIBILITY:-covered}"
REMEDIATION="free space on the database volume (here: remove the filler file); grow the volume"

VOL_DIR="$HOME/v3vol/$TARGET_DB"
IMG="$VOL_DIR/disk.img"
MNT="$VOL_DIR/mnt"
FILL="$MNT/strata_fill.bin"
SD_="$(fault_repo_root)/microservice-lttng-data-collection-scripts"
OV="$SD_/docker-compose.diskfull.yml"

is_armed() { mountpoint -q "$MNT" && docker inspect -f '{{range .Mounts}}{{.Source}} {{end}}' "$(resolve_container "$TARGET_DB")" 2>/dev/null | grep -q "$MNT"; }
free_kb() { df -k --output=avail "$MNT" | tail -1 | tr -d ' '; }
recreate() {   # recreate <override-file-or-empty>
    COMPOSE_OVERRIDE="$1" compose_stack up -d --no-deps --force-recreate "$TARGET_DB" >/dev/null 2>&1
}
wait_db() {
    local c; c="$(resolve_container "$TARGET_DB")"
    for _ in $(seq 1 30); do
        docker exec "$c" mongo --quiet --eval 'db.runCommand({ping:1}).ok' 2>/dev/null | grep -q 1 && return 0
        sleep 2
    done
    return 1
}

case "${1:-}" in
  arm)
    # THE ONLY STEP (with disarm) THAT RESTARTS ANYTHING. Before tracing starts.
    mkdir -p "$MNT"
    if ! mountpoint -q "$MNT"; then
        rm -f "$IMG"
        fallocate -l "${VOL_MB}M" "$IMG"
        mkfs.ext4 -q -m 0 -F "$IMG"
        sudo mount -o loop "$IMG" "$MNT"
        sudo chmod 777 "$MNT"
    fi
    sudo rm -f "$FILL"
    cat > "$OV" <<EOF
# GENERATED by disk_full.sh. Safe to delete; regenerated on every arm.
services:
  $TARGET_DB:
    volumes:
      - $MNT:/data/db
EOF
    recreate "$OV" || { echo "[$FAULT_NAME] compose failed to recreate $TARGET_DB"; exit 1; }
    wait_db || { echo "[$FAULT_NAME] $TARGET_DB did not come up on the small volume"; exit 1; }
    echo "[$FAULT_NAME] armed: $TARGET_DB on its own ${VOL_MB} MB volume, $(( $(free_kb) / 1024 )) MB free"
    ;;
  inject)
    INTENSITY="${2:-aggressive}"
    is_armed || { echo "*** $TARGET_DB is not armed. Run '$0 arm' BEFORE tracing starts."; exit 1; }
    case "$INTENSITY" in
      aggressive) LEAVE_KB=0 ;;        # every free byte
      subtle)     LEAVE_KB=16384 ;;    # 16 MB left: it runs out a little later, by itself
      *) echo "unknown intensity: $INTENSITY"; exit 1 ;;
    esac
    BEFORE_KB="$(free_kb)"
    gt_begin "$INTENSITY" "{\"database\": \"$TARGET_DB\", \"volume_mb\": $VOL_MB, \"free_kb_before\": $BEFORE_KB, \"left_free_kb\": $LEAVE_KB, \"filler\": \"$FILL\", \"container\": \"$(resolve_container "$TARGET_DB")\"}"
    if [[ "$LEAVE_KB" -eq 0 ]]; then
        sudo fallocate -l "${BEFORE_KB}K" "$FILL" 2>/dev/null || true
        sudo dd if=/dev/zero of="$FILL" bs=64K oflag=append conv=notrunc status=none 2>/dev/null || true   # to the last block
    else
        sudo fallocate -l "$(( BEFORE_KB - LEAVE_KB ))K" "$FILL"
    fi
    echo "[$FAULT_NAME] volume filled: $(( BEFORE_KB / 1024 )) MB free -> $(free_kb) kB free"
    ;;
  cleanup)
    sudo rm -f "$FILL"
    echo "[$FAULT_NAME] filler removed: $(( $(free_kb) / 1024 )) MB free"
    gt_end
    ;;
  disarm)
    # Back to the stock deployment. After tracing has ended.
    rm -f "$OV"
    recreate "" || true
    sudo umount "$MNT" 2>/dev/null || true
    rm -rf "$VOL_DIR"
    echo "[$FAULT_NAME] disarmed: $TARGET_DB back on its normal volume"
    ;;
  status)
    c="$(resolve_container "$TARGET_DB")"
    docker ps -a --filter "name=$c" --format '{{.Names}} {{.Status}}'
    is_armed && echo "armed: yes, $(free_kb) kB free on $MNT" || echo "armed: no"
    ;;
  *)
    echo "usage: $0 arm | inject [subtle|aggressive] | cleanup | disarm | status"; exit 1 ;;
esac
