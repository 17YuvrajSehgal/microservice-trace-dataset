#!/bin/bash
# Shared implementation for the code-defect recipes.
#
# Every defect is gated at runtime on STRATA_BUG inside an image built by
# code-defects/build_defect_images.sh. Injecting means swapping ONE service to that image with
# the flag set; cleaning up means putting it back to the stock image.
#
# THE POINT OF THE FLAG. A patched image is not the stock image - different build, different
# layer, possibly a different compiler pass. If the control were the stock service, every
# comparison would measure the rebuild as well as the defect. With the flag, control and fault
# are the same bytes and the only difference is which code path runs.
#
# WHY COMPOSE AND NOT `docker run` (learned the hard way, 2026-09-05)
# -------------------------------------------------------------------
# The first version captured the container's config, did `docker rm -f`, then `docker run`.
# When the run failed, the service was simply GONE - the stack was left broken with no
# front-end at all. Worse, the containers it did create had no compose labels, so compose
# refused to recreate them afterwards ("container name is already in use") and the stack could
# not be repaired without manual removal.
#
# Remove-then-create is not safe for something that runs unattended 100+ times.
#
# Compose already knows the network, the aliases, the command, the healthchecks and the
# dependencies. So a defect is now a one-service override file added to the same stack
# definition, applied with `up -d --no-deps <service>`. Compose recreates the container itself,
# in place, and a failure leaves the previous container running rather than nothing at all.
#
# A recipe sources this file, sets DEFECT_* and calls code_defect_dispatch "$@".

_cd_repo() { (cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" && pwd); }

# ONE definition of the stack, in fault_lib.sh.
#
# This file used to carry its own copy of the 7-file compose invocation. Two copies of an
# ordering that matters is exactly how the v1 drivers drifted into two different fault
# matrices - the bug that left Sock Shop with 50 runs and Train Ticket with 43. A duplicate
# that is correct today is still a duplicate.
_cd_compose() { COMPOSE_OVERRIDE="${_CD_OVERRIDE:-}" compose_stack "$@"; }

code_defect_require_image() {
    if ! docker image inspect "$DEFECT_IMAGE" >/dev/null 2>&1; then
        echo "*** $DEFECT_IMAGE has not been built."
        echo "*** Run: bash faults/code-defects/build_defect_images.sh"
        exit 1
    fi
}

# Swap one service to <image> with STRATA_BUG=<bug>. Passing an empty image restores stock.
code_defect_apply() {   # code_defect_apply <bug-name-or-none> [image-or-empty-for-stock]
    local bug="$1" image="${2:-}"
    local sd; sd="$(_cd_repo)/microservice-lttng-data-collection-scripts"
    local ov="$sd/docker-compose.codedefect.yml"

    if [[ -n "$image" ]]; then
        # A minimal override: only the fields the defect needs. Everything else - network,
        # aliases, command, depends_on - still comes from the stack definition.
        cat > "$ov" <<EOF
# GENERATED by code_defect_lib.sh. Safe to delete; regenerated on every inject.
services:
  $DEFECT_SERVICE:
    image: $image
    environment:
      - STRATA_BUG=$bug
EOF
        _CD_OVERRIDE="$ov"
    else
        rm -f "$ov"
        _CD_OVERRIDE=""
    fi

    # Remove any container compose renamed out of the way in a previous failed recreate.
    # They are inert but they shadow the expected name and confuse every later lookup.
    docker ps -a --format '{{.Names}}'         | grep -E "^[0-9a-f]{12}_.*_${DEFECT_SERVICE}_1$"         | xargs -r docker rm -f >/dev/null 2>&1 || true

    if ! _cd_compose up -d --no-deps --force-recreate "$DEFECT_SERVICE" >/dev/null 2>&1; then
        echo "[$FAULT_NAME] compose failed to recreate $DEFECT_SERVICE - stack left as it was"
        _cd_compose up -d --no-deps "$DEFECT_SERVICE" >/dev/null 2>&1 || true
        return 1
    fi

    # Ask COMPOSE which container is the service, rather than assuming the name.
    #
    # Measured: after a failed recreate, compose leaves the old container renamed with a hash
    # prefix - `0425f955070a_docker-compose_front-end_1`. Looking up the exact name then finds
    # nothing and reports "did not stay up" for a service that is running perfectly well. That
    # turned three working defects into failures in one smoke run.
    local cname
    cname="$(_cd_compose ps -q "$DEFECT_SERVICE" 2>/dev/null | head -1)"
    [[ -z "$cname" ]] && cname="$(resolve_container "$DEFECT_SERVICE")"
    sleep 6
    if [[ "$(docker inspect -f '{{.State.Running}}' "$cname" 2>/dev/null)" != "true" ]]; then
        echo "[$FAULT_NAME] $DEFECT_SERVICE did not stay up with STRATA_BUG=$bug - logs:"
        docker logs "$cname" 2>&1 | tail -20
        return 1
    fi
    echo "[$FAULT_NAME] $DEFECT_SERVICE running ${image:-stock} with STRATA_BUG=${bug}"
}

code_defect_dispatch() {
    case "${1:-}" in
      inject)
        code_defect_require_image
        code_defect_apply "$DEFECT_BUG" "$DEFECT_IMAGE" || exit 1
        local prov commit="unknown"
        prov="$HOME/fault-state/code_defect_${DEFECT_SERVICE}.provenance.json"
        [[ -f "$prov" ]] && commit=$(python3 -c "import json;print(json.load(open('$prov'))['commit'])" 2>/dev/null || echo unknown)
        gt_begin "${2:-aggressive}" "{\"kind\": \"code_defect\", \"service\": \"$DEFECT_SERVICE\", \"image\": \"$DEFECT_IMAGE\", \"bug\": \"$DEFECT_BUG\", \"commit\": \"$commit\", \"mechanism\": \"$DEFECT_MECHANISM\", \"correct_fix\": \"$DEFECT_FIX\", \"pairs_with\": \"$DEFECT_PAIRS_WITH\", \"control\": \"same image with STRATA_BUG=none\"}"
        ;;
      control)
        # The paired healthy run: SAME image, defect off. Not a `normal` run - a control run.
        code_defect_require_image
        code_defect_apply none "$DEFECT_IMAGE" || exit 1
        ;;
      cleanup)
        # back to the stock image from the stack definition
        code_defect_apply none "" || true
        gt_end
        ;;
      status)
        local cname; cname="$(resolve_container "$DEFECT_SERVICE")"
        docker ps --filter "name=$cname" --format '{{.Names}} {{.Image}} {{.Status}}'
        docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$cname" 2>/dev/null | grep STRATA_BUG || echo "STRATA_BUG unset (stock)"
        ;;
      *) echo "usage: $0 inject [subtle|aggressive] | control | cleanup | status"; exit 1 ;;
    esac
}
