#!/usr/bin/env python3
"""Walk the dataset and write an inventory a person can read.

One row per run, straight from each run's own ground_truth.json and verification.json. Nothing
is inferred and nothing is hard-coded, so the inventory cannot drift from the data the way a
hand-written table does - which is exactly how ten Sock Shop families went missing for two days
in September without anything failing.

Writes INVENTORY.csv and a short README.md into the dataset root.

    python make_inventory.py --root /scratch/yuvraj17/stratatrace/dataset
"""
from __future__ import annotations

import argparse
import csv
import json
import os
from collections import Counter, defaultdict

MODALITIES = ("kernel", "otlp", "logs", "meta")


def read_json(p):
    try:
        with open(p, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return {}


def scan(runs_root: str):
    rows = []
    for app in sorted(os.listdir(runs_root)):
        ap = os.path.join(runs_root, app)
        if not os.path.isdir(ap) or app.startswith("."):
            continue
        for fam in sorted(os.listdir(ap)):
            fp = os.path.join(ap, fam)
            if not os.path.isdir(fp):
                continue
            for rid in sorted(os.listdir(fp)):
                rp = os.path.join(fp, rid)
                if not os.path.isdir(rp) or rid.endswith("_metrics"):
                    continue
                gt = read_json(os.path.join(rp, "ground_truth.json"))
                ve = read_json(os.path.join(rp, "verification.json"))
                f = gt.get("fault") or {}
                win = ve.get("injection_window_utc") or []
                rows.append({
                    "app": app,
                    "family": fam,
                    "run_id": rid,
                    # a `normal` run has no fault, so it has no ground_truth.json. That is
                    # correct, not missing data - they are the reference runs.
                    "kind": "baseline" if not gt else "fault",
                    "fault_name": f.get("name", ""),
                    "intensity": f.get("intensity", ""),
                    "scope": f.get("scope", ""),
                    "target_service": f.get("target_service", ""),
                    "expected_winning_modality": f.get("expected_winning_modality", ""),
                    "injection_start_utc": f.get("injection_start_utc", ""),
                    "injection_end_utc": f.get("injection_end_utc", ""),
                    "verification": ve.get("verification_status", ""),
                    "operator_review_required": ve.get("operator_review_required", ""),
                    "verify_window_start": win[0] if len(win) > 0 else "",
                    "verify_window_end": win[1] if len(win) > 1 else "",
                    "has_all_4_modalities": all(
                        os.path.isdir(os.path.join(rp, m)) for m in MODALITIES),
                    "has_metrics_sidecar": os.path.isdir(rp + "_metrics"),
                    "path": os.path.relpath(rp, os.path.dirname(runs_root)),
                })
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/scratch/yuvraj17/stratatrace/dataset")
    a = ap.parse_args()

    runs_root = os.path.join(a.root, "runs")
    rows = scan(runs_root)
    if not rows:
        print("no runs found under %s" % runs_root)
        return 1

    cols = list(rows[0].keys())
    csv_path = os.path.join(a.root, "INVENTORY.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    by_app = Counter(r["app"] for r in rows)
    by_kind = Counter(r["kind"] for r in rows)
    verif = Counter(r["verification"] or "(baseline - none)" for r in rows)
    fams = defaultdict(set)
    for r in rows:
        fams[r["app"]].add(r["family"])
    incomplete = [r for r in rows if not r["has_all_4_modalities"]]
    nometrics = [r for r in rows if not r["has_metrics_sidecar"]]

    per_family = defaultdict(lambda: Counter())
    for r in rows:
        per_family[r["app"]][r["family"]] += 1

    L = []
    L.append("# StrataTrace v2 - the dataset")
    L.append("")
    L.append("Everything about the dataset is under this one directory. Generated by")
    L.append("`transfer/make_inventory.py`, straight from each run's own files - so if this")
    L.append("disagrees with the runs, this file is the thing that is wrong.")
    L.append("")
    L.append("## What is here")
    L.append("")
    L.append("| directory | what | size |")
    L.append("|---|---|---|")
    L.append("| `runs/` | the extracted runs. **This is what analysis reads.** | 7.7 TB |")
    L.append("| `archives/` | the same runs as `.tar.gz`, one per family. The durable form | 844 GB |")
    L.append("| `archives/provenance/` | Prometheus TSDB, campaign manifests, collection logs, VM images | |")
    L.append("| `index/` | per-run kernel event count tables, built by `build_ctf_index.py` | 42 MB |")
    L.append("| `INVENTORY.csv` | one row per run, every field below | |")
    L.append("")
    L.append("## How many runs")
    L.append("")
    L.append("| | %s |" % " | ".join(sorted(by_app)))
    L.append("|---|%s|" % "|".join("---" for _ in by_app))
    L.append("| runs | %s |" % " | ".join(str(by_app[k]) for k in sorted(by_app)))
    L.append("| families | %s |" % " | ".join(str(len(fams[k])) for k in sorted(by_app)))
    L.append("")
    L.append("**%d runs in total.** %d carry an injected fault, %d are `normal` reference runs."
             % (len(rows), by_kind["fault"], by_kind["baseline"]))
    L.append("")
    L.append("A `normal` run has no `ground_truth.json` or `verification.json`, because there is")
    L.append("no fault to describe or verify. That is correct, not missing data.")
    L.append("")
    L.append("## Completeness")
    L.append("")
    L.append("| check | result |")
    L.append("|---|---|")
    L.append("| all four modality dirs (`kernel`, `otlp`, `logs`, `meta`) | **%d / %d** |"
             % (len(rows) - len(incomplete), len(rows)))
    L.append("| a `<run_id>_metrics/` sidecar | **%d / %d** |"
             % (len(rows) - len(nometrics), len(rows)))
    L.append("")
    if incomplete:
        L.append("Runs missing a modality:")
        for r in incomplete:
            L.append("- `%s`" % r["run_id"])
        L.append("")
    L.append("## Verification verdicts")
    L.append("")
    L.append("| verdict | runs |")
    L.append("|---|---|")
    for k, n in verif.most_common():
        L.append("| `%s` | %d |" % (k, n))
    L.append("")
    L.append("`no_metric_signature` means the fault is present and was measured to have no")
    L.append("metric signature. For kernel-trace work those are the most interesting runs, not")
    L.append("the weakest ones.")
    L.append("")
    L.append("## Runs per family")
    L.append("")
    for app in sorted(per_family):
        L.append("**%s**" % app)
        L.append("")
        L.append("| family | runs |")
        L.append("|---|---|")
        for fam, n in sorted(per_family[app].items()):
            L.append("| %s | %d |" % (fam, n))
        L.append("")
    L.append("## What one run holds")
    L.append("")
    L.append("```")
    L.append("runs/<app>/<family>/<run_id>/")
    L.append("    kernel/kernel/      LTTng CTF trace, expanded (~23 GB)")
    L.append("    otlp/               OTLP spans")
    L.append("    logs/               container logs")
    L.append("    meta/               clock anchors and cgroup snapshots during the run")
    L.append("    ust/                userspace tracepoints")
    L.append("    ground_truth.json   what was injected, where, and when   (fault runs only)")
    L.append("    verification.json   whether it was measured to have worked (fault runs only)")
    L.append("    verification.png    the evidence plot")
    L.append("    MANIFEST.json, SHA256SUMS")
    L.append("runs/<app>/<family>/<run_id>_metrics/     ~440 Prometheus series")
    L.append("runs/<app>/<family>/<run_id>_load.csv     client-side requests")
    L.append("```")
    L.append("")
    L.append("## Things that will bite you")
    L.append("")
    L.append("1. **`runs/` and `archives/` are different things and have fallen out of step")
    L.append("   before.** In September ten Sock Shop families were retired from `runs/` and")
    L.append("   their replacements never extracted. Nothing failed - queries just answered")
    L.append("   \"0 runs\". If you retire anything, extract its replacement in the same breath,")
    L.append("   then re-run this script and check the counts.")
    L.append("2. **babeltrace prints and reads timestamps in the local zone.** Use `--clock-gmt`")
    L.append("   or `TZ=UTC`. Everything else in a run is UTC, so without it nothing lines up.")
    L.append("3. **babeltrace2 2.0.4 cannot read these traces.** Check")
    L.append("   `tools/bt21.sh --version` says 2.1.2.")
    L.append("4. Retired runs are in `../attic/`, not here. They are not part of the dataset.")
    L.append("")
    L.append("## Old paths")
    L.append("")
    L.append("`data/stratatrace-v2` and `data/ctf-index` are symlinks into here, so anything")
    L.append("still pointing at them keeps working.")
    L.append("")

    readme = os.path.join(a.root, "README.md")
    with open(readme, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))

    print("wrote %s  (%d rows)" % (csv_path, len(rows)))
    print("wrote %s" % readme)
    print()
    print("runs: %d   fault: %d   baseline: %d"
          % (len(rows), by_kind["fault"], by_kind["baseline"]))
    for k in sorted(by_app):
        print("  %-12s %3d runs, %2d families" % (k, by_app[k], len(fams[k])))
    print("missing a modality: %d   missing metrics sidecar: %d"
          % (len(incomplete), len(nometrics)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
